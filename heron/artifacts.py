"""
Paths and checksums for the released model artifacts.

Every script in the repository resolves checkpoint paths through this module,
so the whole pipeline is redirected with one environment variable:

    export HERON_WEIGHTS=/path/to/weights      # default: <repo>/weights

Artifacts (see weights/SHA256SUMS and docs/WEIGHTS.md):

    mbhb_flow.pt            stage-2 alert flow (108M-parameter NSF, sky-GNPE)
    mbhb_norm.pt            feature normalization of the alert flow
    mbhb_dataset_info.json  heterodyne grid + reference kernel the flow was trained with
    recal_map.npz           post-hoc per-parameter calibration map
    ucb_flow.pt             stage-3 UCB window flow (785k parameters)
    ucb_response.npz        calibrated per-bin UCB line response (foreground augmentation)
    yolo_lisa_best.pt       stage-1 spectrogram detector
    yolo26n_base.pt         pretrained base checkpoint the detector is fine-tuned from
"""
import hashlib
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS = Path(os.environ.get('HERON_WEIGHTS', ROOT / 'weights'))

ART = {
    'yolo':          WEIGHTS / 'yolo_lisa_best.pt',
    'yolo_base':     WEIGHTS / 'yolo26n_base.pt',
    'mbhb_flow':     WEIGHTS / 'mbhb_flow.pt',
    'mbhb_norm':     WEIGHTS / 'mbhb_norm.pt',
    'mbhb_info':     WEIGHTS / 'mbhb_dataset_info.json',
    'mbhb_recal':    WEIGHTS / 'recal_map.npz',
    'ucb_flow':      WEIGHTS / 'ucb_flow.pt',
    'ucb_response':  WEIGHTS / 'ucb_response.npz',
}

# Data. Only the held-out TEST splits are needed to reproduce the paper's
# validations from the released weights; they are distributed as a small
# archive (docs/DATA.md). The training sets are regenerated by the data stage.
DATA = Path(os.environ.get('HERON_DATA', ROOT / 'data'))
MBHB_DATA = str(DATA / 'mbhb')
MBHB_DATA_RIDGE = str(DATA / 'mbhb_ridge')   # test split of the earlier MBHB set (docs/DATA.md)
UCB_DATA = str(DATA / 'ucb')

# Outputs. Everything a run produces goes under results/ (untracked):
#   results/products/  numerical products (npz/npy/json) behind every figure
#   results/figures/   the figures
# paper_products/ (tracked) holds the exact products behind the published
# figures, so each figure can be redrawn without a GPU.
RESULTS = Path(os.environ.get('HERON_RESULTS', ROOT / 'results'))
PRODUCTS = RESULTS / 'products'
FIGURES = RESULTS / 'figures'
PAPER_PRODUCTS = ROOT / 'paper_products'


def product_out(name):
    """Path for a numerical product written by this run (results/products/)."""
    PRODUCTS.mkdir(parents=True, exist_ok=True)
    return str(PRODUCTS / name)


def figure_out(name):
    """Path for a figure written by this run (results/figures/)."""
    FIGURES.mkdir(parents=True, exist_ok=True)
    return str(FIGURES / name)


def product_in(name, verbose=True):
    """Path of a numerical product to read: your own rerun (results/products/)
    if present, otherwise the published one (paper_products/)."""
    for d, tag in ((PRODUCTS, 'this run'), (PAPER_PRODUCTS, 'published')):
        if (d / name).exists():
            if verbose:
                print(f"[products] {name}: {tag} ({d / name})")
            return str(d / name)
    raise SystemExit(f"product '{name}' not found in {PRODUCTS} or {PAPER_PRODUCTS}; "
                     f"see docs/REPRODUCE.md for the command that generates it.")


