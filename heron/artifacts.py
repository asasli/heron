def load_kernel(data_dir=None):
    """Base reference kernel (frac_Mc, log_q, chi, t_floor_sec, t_frac_of_tpre)
    the alert flow was trained with.

    Resolution order: an explicit dataset directory (its dataset_info.json, as
    written by pe_smbhb/data_mbhb.py), then the copy released with the weights,
    then the constant in pe_smbhb/data_mbhb.py. All three are identical for the
    released model; the order only matters for a model you retrain yourself."""
    for p in ([Path(data_dir) / 'dataset_info.json'] if data_dir else []) + [ART['mbhb_info']]:
        if p.exists():
            k = json.loads(p.read_text())['kernel']
            return k.get('base', k.get('narrow'))
    from pe_smbhb.data_mbhb import KERNEL
    return dict(KERNEL['base'])


def sha256(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for b in iter(lambda: f.read(chunk), b''):
            h.update(b)
    return h.hexdigest()


def verify(strict=True, verbose=True):
    """Check every artifact against weights/SHA256SUMS. Returns True if all match."""
    sums = WEIGHTS / 'SHA256SUMS'
    if not sums.exists():
        raise SystemExit(f"{sums} not found: fetch the released weights with "
                         f"`heron download` (docs/WEIGHTS.md).")
    ok = True
    for line in sums.read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        digest, name = line.split()
        p = WEIGHTS / name
        if not p.exists():
            status, good = 'MISSING', False
        else:
            good = sha256(p) == digest
            status = 'ok' if good else 'CHECKSUM MISMATCH'
        ok &= good
        if verbose:
            print(f"  {name:26s} {status}")
    if strict and not ok:
        raise SystemExit("weights verification failed")
    return ok


def require(*keys):
    """Fail early, with a useful message, if an artifact is absent."""
    missing = [str(ART[k]) for k in keys if not ART[k].exists()]
    if missing:
        raise SystemExit("missing model artifact(s):\n  " + "\n  ".join(missing)
                         + "\nFetch the released weights with `heron download` "
                           "(docs/WEIGHTS.md), or point HERON_WEIGHTS at a bundle "
                           "written by `heron train`.")


if __name__ == '__main__':
    print(f"weights directory: {WEIGHTS}")
    verify()
    print("all artifacts verified")
