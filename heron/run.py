"""
HERON training and validation driver: every stage from data generation to the
validated weights bundle, defined by one YAML file.

    python -m heron.run --config config/heron.yaml --stage all       # the published configuration (days, ~1.8 TB)
    python -m heron.run --config config/smoke.yaml --stage all       # the same code path at toy scale (~10 min)
    python -m heron.run --config config/heron.yaml --stage validate --weights released
    python -m heron.run --config config/heron.yaml --dry-run         # print every command

Stages, in order:

    yolo-data      spectrogram images for the detector            (yolo/dataset_generator.py)
    yolo-train     fine-tune the detector                         (yolo/train_yolo.py)
    ucb-data       UCB windows                                    (pe_ucb/data_ucb.py)
    ucb-train      UCB window flow                                (pe_ucb/train_flow.py)
    ucb-response   calibrated UCB line response                   (evaluation/calibrate_ucb.py)
    mbhb-data      heterodyned MBHB training sets                 (pe_smbhb/data_mbhb.py)
    mbhb-train     alert flow, one run per training phase         (pe_smbhb/train_flow.py)
    recal          calibration set + post-hoc calibration map     (evaluation/pp_marginalized.py, fit_recalibration.py)
    export         checksums + manifest of the weights bundle
    infer          end-to-end pipeline on the Sangria Case-1 event (heron/pipeline.py)
    validate       the validations behind the paper's figures     (evaluation/)

Groups: `data` (the three data stages), `train` (yolo-train ... recal, export),
`all`. Every stage writes its artifact into <out>/weights with the same file
names as the released bundle, so `HERON_WEIGHTS=<out>/weights` points the whole
repository at the retrained models. A stage is skipped when its output exists
(`--force` reruns it). `--weights released` runs `infer` and `validate` on the
released weights instead of the bundle of this run.

All randomness is seeded from the YAML. Data generation is bit-reproducible;
network training is reproducible up to GPU non-determinism (docs/REPRODUCE.md).
"""
import argparse
import datetime
import json
import os
import shutil
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def quote(value):
    """Quote one command argument for display and shlex parsing."""
    return shlex.quote(str(value))

STAGES = ['yolo-data', 'yolo-train', 'ucb-data', 'ucb-train', 'ucb-response',
          'mbhb-data', 'mbhb-train', 'recal', 'export', 'infer', 'validate']
GROUPS = {
    'data': ['yolo-data', 'ucb-data', 'mbhb-data'],
    'train': ['yolo-train', 'ucb-train', 'ucb-response', 'mbhb-train', 'recal', 'export'],
    'all': STAGES,
}


class Run:
    def __init__(self, cfg, force=False, dry=False, weights='auto'):
        self.cfg, self.force, self.dry = cfg, force, dry
        self.out = (ROOT / cfg['out']).resolve()
        self.bundle = self.out / 'weights'
        self.results = self.out / 'results'
        self.logs = self.out / 'logs'
        self.device = cfg.get('device', 'cuda:0')
        self.py = sys.executable
        self.weights_mode = weights
        if not dry:
            for d in (self.bundle, self.results, self.logs):
                d.mkdir(parents=True, exist_ok=True)

    # helpers
    def env(self, released=False):
        e = dict(os.environ)
        e['HERON_RESULTS'] = str(self.results)
        # where the validations find the test splits: the splits generated by
        # this run, or the released ones when the released weights are checked
        root = (self.cfg.get('released_data_root') if released else None) or self.cfg.get('data_root')
        if root:
            e['HERON_DATA'] = str((ROOT / root).resolve())
        if not released:
            e['HERON_WEIGHTS'] = str(self.bundle)
        return e

    def sh(self, cmd, log, env=None):
        """Run one command from the checkout and capture output in its log."""
        print(f"  $ {cmd}", flush=True)
        if self.dry:
            return
        logf = self.logs / log
        with open(logf, 'w') as f:
            f.write(f"# {datetime.datetime.now().isoformat(timespec='seconds')}\n# {cmd}\n")
            f.flush()
            r = subprocess.run(shlex.split(cmd), cwd=ROOT, env=env or self.env(),
                               stdout=f, stderr=subprocess.STDOUT)
        if r.returncode != 0:
            tail = '\n'.join(logf.read_text().splitlines()[-15:])
            raise SystemExit(f"stage command failed ({r.returncode}): {cmd}\n--- {logf} ---\n{tail}")

    def have(self, path, what):
        if (ROOT / path).is_file() and not self.force:
            print(f"  [skip] {what}: {path} exists (use --force to redo)")
            return True
        return False

    def put(self, src, name):
        if self.dry:
            return
        shutil.copy2(ROOT / src, self.bundle / name)
        print(f"  [bundle] {name} <- {src}")

    def use_released(self):
        if self.weights_mode == 'released':
            return True
        if self.weights_mode == 'trained':
            return False
        return not (self.bundle / 'mbhb_flow.pt').exists()

    # yolo
    def yolo_data(self):
        d = self.cfg['yolo']['dataset']
        if self.have(Path(d['dir']) / 'dataset.yaml', 'detector dataset'):
            return
        self.sh(f"{quote(self.py)} -m yolo.dataset_generator --output {quote(d['dir'])} --n-train {quote(d['n_train'])} "
                f"--n-val {quote(d['n_val'])} --n-test {quote(d['n_test'])} --seed {quote(d['seed'])}", 'yolo_data.log')

    def yolo_train(self):
        y = self.cfg['yolo']; t = y['train']
        proj = self.out / 'yolo'
        if not self.have(self.bundle / 'yolo_lisa_best.pt', 'detector'):
            from heron.artifacts import YOLO_BASE
            base = y.get('base', YOLO_BASE)
            self.sh(f"{quote(self.py)} -m yolo.train_yolo --data-dir {quote(y['dataset']['dir'])} --epochs {quote(t['epochs'])} "
                    f"--batch-size {quote(t['batch'])} --patience {quote(t['patience'])} --seed {quote(t['seed'])} "
                    f"--img-size {quote(t.get('img_size', 640))} --workers {quote(t.get('workers', 8))} "
                    f"--pretrained {quote(base)} --project {quote(proj)} --device {quote(self.device.replace('cuda:', ''))}",
                    'yolo_train.log')
            self.put(proj / 'yolo_lisa_best.pt', 'yolo_lisa_best.pt')
            self.put(base, 'yolo26n_base.pt')

    # ucb
    def ucb_data(self):
        d = self.cfg['ucb']['dataset']
        if self.have(Path(d['dir']) / 'test' / 'metadata.json', 'UCB dataset'):   # written last
            return
        self.sh(f"{quote(self.py)} -m pe_ucb.data_ucb --output-dir {quote(d['dir'])} --n-train {quote(d['n_train'])} "
                f"--n-val {quote(d['n_val'])} --n-test {quote(d['n_test'])} --seed {quote(d['seed'])}", 'ucb_data.log')

    def ucb_train(self):
        u = self.cfg['ucb']; t = u['train']
        if self.have(self.bundle / 'ucb_flow.pt', 'UCB flow'):
            return
        save = self.out / 'ucb'
        self.sh(f"{quote(self.py)} -m pe_ucb.train_flow --data {quote(u['dataset']['dir'])} --tag ucb --epochs {quote(t['epochs'])} "
                f"--batch-size {quote(t['batch'])} --lr {quote(t['lr'])} --seed {quote(t['seed'])} --save-dir {quote(save)} "
                f"--device {quote(self.device)}", 'ucb_train.log')
        self.put(save / 'ucb_flow_ucb_best.pt', 'ucb_flow.pt')

    def ucb_response(self):
        if self.have(self.bundle / 'ucb_response.npz', 'UCB response'):
            return
        self.sh(f"{quote(self.py)} evaluation/calibrate_ucb.py", 'ucb_response.log')
        self.put(self.results / 'products' / 'ucb_response.npz', 'ucb_response.npz')

    # mbhb
    def _chunks(self, d):
        first = d.get('chunk_first', 1)
        return [f"{d['dir']}_c{i}" for i in range(first, first + d['n_chunks'])]

    def mbhb_data(self):
        for name, d in self.cfg['mbhb']['datasets'].items():
            wide = '--wide-spin-ref' if d.get('wide_spin_ref') else ''
            if not self.have(Path(d['dir']) / 'test' / 'metadata.json', f"MBHB set '{name}' (base)"):   # written last
                self.sh(f"{quote(self.py)} pe_smbhb/data_mbhb.py --output-dir {quote(d['dir'])} --n-train {quote(d['n_train'])} "
                        f"--n-val {quote(d['n_val'])} --n-test {quote(d['n_test'])} --seed {quote(d['base_seed'])} {wide}",
                        f"mbhb_data_{name}_base.log")
            first = d.get('chunk_first', 1)
            for k, c in enumerate(self._chunks(d)):
                i = first + k
                if self.have(Path(c) / 'train' / 'metadata.json', f"MBHB set '{name}' chunk {i}"):
                    continue
                self.sh(f"{quote(self.py)} pe_smbhb/data_mbhb.py --output-dir {quote(c)} --n-train {quote(d['n_train'])} "
                        f"--n-val 0 --n-test 0 --seed {quote(d['chunk_seed0'] + i)} {wide}",
                        f"mbhb_data_{name}_c{i}.log")

    def mbhb_train(self):
        m = self.cfg['mbhb']; a = m['arch']
        if all((self.bundle / name).is_file() for name in
               ('mbhb_flow.pt', 'mbhb_norm.pt', 'mbhb_dataset_info.json')) and not self.force:
            return
        save = self.out / 'mbhb'
        prev, last_data = None, None
        for ph in m['phases']:
            d = m['datasets'][ph['data']]
            ck = save / f"sbi_het_{ph['tag']}_bestsky.pt"
            # the checkpoint exists from the first epoch on, so completion of a
            # phase is recorded separately: an interrupted phase is run again
            done = save / f"{ph['tag']}.done"
            if not (ck.is_file() and (save / f"norm_stats_het_{ph['tag']}.pt").is_file()
                    and self.have(done, f"phase {ph['tag']}")):
                flags = '--residual-targets --ucb-cond --sky-gnpe' + (' --abs-spins' if ph.get('abs_spins') else '')
                resume = f"--resume {quote(prev)}" if prev else ''
                stop = f"--stop-epoch {quote(ph['stop_epoch'])}" if ph.get('stop_epoch') else ''
                self.sh(f"{quote(self.py)} -m pe_smbhb.train_flow --data-dir {quote(d['dir'])} "
                        f"--train-chunks {' '.join(quote(c) for c in self._chunks(d))} --chunk-epochs {quote(m.get('chunk_epochs', 4))} "
                        f"--tag {quote(ph['tag'])} {resume} --epochs {quote(ph['epochs'])} {stop} "
                        f"--batch-size {quote(m.get('batch', 256))} --lr {quote(ph['lr'])} "
                        f"--weight-decay {quote(m.get('weight_decay', 1e-3))} --patience {quote(ph.get('patience', 60))} "
                        f"--enc-hidden {quote(a['enc_hidden'])} --enc-blocks {quote(a['enc_blocks'])} "
                        f"--context-dim {quote(a['context_dim'])} --n-transforms {quote(a['n_transforms'])} "
                        f"--flow-hidden {quote(a['flow_hidden'])} --flow-bins {quote(a['flow_bins'])} --bank-k {quote(a['bank_k'])} "
                        f"--sky-weight {quote(m.get('sky_weight', 0.5))} {flags} --seed {quote(ph.get('seed', 0))} "
                        f"--ucb-response {quote(self.bundle / 'ucb_response.npz')} --save-dir {quote(save)} "
                        f"--device {quote(self.device)}", f"mbhb_train_{ph['tag']}.log")
                if not self.dry:
                    norm = save / f"norm_stats_het_{ph['tag']}.pt"
                    if not ck.is_file() or not norm.is_file():
                        raise SystemExit(f"phase {ph['tag']} did not produce {ck} and {norm}")
                    done.write_text(datetime.datetime.now().isoformat(timespec='seconds') + '\n')
            prev, last_data = ck, d
            last_tag = ph['tag']
        self.put(prev, 'mbhb_flow.pt')
        self.put(save / f"norm_stats_het_{last_tag}.pt", 'mbhb_norm.pt')
        self.put(Path(last_data['dir']) / 'dataset_info.json', 'mbhb_dataset_info.json')

    def recal(self):
        r = self.cfg['recal']
        if self.have(self.bundle / 'recal_map.npz', 'calibration map'):
            return
        prod = self.results / 'products'
        common = (f"--k-ref 1 --ref-scale {quote(r.get('ref_scale', 1.0))} --n-ucb {quote(r['n_ucb'])} "
                  f"--n-per {quote(r.get('n_per', 400))} --device {quote(self.device)}")
        self.sh(f"{quote(self.py)} evaluation/pp_marginalized.py {common} --n-events {quote(r['n_cal'])} "
                f"--seed-base {quote(r['seed_base_cal'])} --out-ranks {quote(prod / 'pp_ranks_cal.npz')}", 'recal_cal_set.log')
        self.sh(f"{quote(self.py)} evaluation/pp_marginalized.py {common} --n-events {quote(r['n_test'])} "
                f"--seed-base 0 --out-ranks {quote(prod / 'pp_ranks.npz')}", 'recal_test_set.log')
        self.sh(f"{quote(self.py)} evaluation/fit_recalibration.py --cal {quote(prod / 'pp_ranks_cal.npz')} "
                f"--test {quote(prod / 'pp_ranks.npz')}", 'recal_fit.log')
        self.put(prod / 'recal_map.npz', 'recal_map.npz')

    def export(self):
        """Checksums + manifest: the bundle becomes a drop-in weights directory."""
        if self.dry:
            print(f"  (would write {self.bundle}/SHA256SUMS and manifest.json)")
            return
        from heron.artifacts import ART, sha256
        missing = [p.name for p in ART.values() if not (self.bundle / p.name).is_file()]
        if missing:
            raise SystemExit(f"cannot export incomplete weights bundle: {', '.join(missing)}")
        names = sorted(p.name for p in self.bundle.iterdir()
                       if p.suffix in ('.pt', '.npz', '.json') and p.name != 'manifest.json')
        (self.bundle / 'SHA256SUMS').write_text(
            ''.join(f"{sha256(self.bundle / n)}  {n}\n" for n in names))
        try:
            commit = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=ROOT, capture_output=True,
                                    text=True).stdout.strip() or None
        except Exception:
            commit = None
        ver = {}
        for mod in ('torch', 'zuko', 'cupy', 'ultralytics', 'numpy'):
            try:
                ver[mod] = __import__(mod).__version__
            except Exception:
                ver[mod] = None
        (self.bundle / 'manifest.json').write_text(json.dumps(dict(
            created=datetime.datetime.now().isoformat(timespec='seconds'),
            code_commit=commit, versions=ver, config=self.cfg, files=names), indent=1, default=str))
        print(f"  bundle: {self.bundle}  ({len(names)} files)")
        print(f"  use it with:  export HERON_WEIGHTS={self.bundle}")

    # infer / validate
    def infer(self):
        i = self.cfg.get('infer', {})
        rel = self.use_released()
        print(f"  weights: {'released' if rel else self.bundle}")
        self.sh(f"{quote(self.py)} -m heron.pipeline --simulate --case {quote(i.get('case', 1))} --n-ucb {quote(i.get('n_ucb', 30))} "
                f"--detector {quote(i.get('detector', 'oracle'))} --skip-pointing --out {quote(self.out / 'pipeline')} "
                f"--device {quote(self.device)}", 'infer.log', env=self.env(released=rel))

    def validate(self):
        v = self.cfg['validate']
        rel = self.use_released()
        print(f"  weights: {'released' if rel else self.bundle}")
        dev = f"--device {quote(self.device)}"
        # the population sky-area products of the paper were computed on the test
        # split of the `ridge` set; use it when the configuration names it
        sky_data = ''
        if v.get('sky_testset'):
            d = Path(self.env(released=rel)['HERON_DATA']) / v['sky_testset']
            if (d / 'test').exists() or self.dry:
                sky_data = f" --data {quote(d)}"
            else:
                print(f"  note: {d}/test not found; sky-area validations use the default test split")
        jobs = [
            ('pp', f"evaluation/pp_marginalized.py --k-ref 1 --ref-scale {quote(v.get('ref_scale', 1.0))} "
                   f"--n-ucb {quote(v['n_ucb'])} --n-events {quote(v['pp_events'])} {dev}"),
            ('recal_check', "evaluation/fit_recalibration.py --test "
                            f"{quote(self.results / 'products' / 'pp_ranks.npz')} "
                            f"--out-map {quote(self.results / 'products' / 'recal_map_refit.npz')}"),
            ('calibration_summary', "evaluation/fig_calibration_summary.py"),
            ('sky_area', f"evaluation/eval_skygnpe.py --rounds 4 --stride {quote(v['sky_stride'])}{sky_data} {dev}"),
            ('robust', f"evaluation/eval_robust.py --rounds 4 --n-events {quote(v['robust_events'])}{sky_data} {dev}"),
            ('countdown', f"evaluation/countdown.py --max-per-bin {quote(v['countdown_per_bin'])} {dev}"),
            ('ucb_flow', f"evaluation/eval_ucb_flow.py --n-pp {quote(v['ucb_pp'])} {dev}"),
            ('ucb_subtract', f"evaluation/ucb_subtract_test.py --n {quote(v['subtract_n'])} --fstat {dev}"),
            ('recon_sky', "evaluation/recon_sky_test.py --case 1"),
        ]
        skip = set(v.get('skip', []))
        failed = []
        for name, cmd in jobs:
            if name in skip:
                continue
            print(f"[validate:{name}]")
            try:
                self.sh(f"{quote(self.py)} {cmd}", f"validate_{name}.log", env=self.env(released=rel))
            except SystemExit as e:
                failed.append(name)
                print(f"  !! {name} failed\n{e}")
        if failed:
            raise SystemExit(f"validation jobs failed: {failed}")


def main(argv=None):
    ap = argparse.ArgumentParser(description="HERON training and validation driver",
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    ap.add_argument('--config', default=str(ROOT / 'config/heron.yaml'))
    ap.add_argument('--stage', default='all',
                    help=f"comma-separated stages or groups: {', '.join(STAGES)}; groups: data, train, all")
    ap.add_argument('--force', action='store_true', help='rerun stages whose outputs exist')
    ap.add_argument('--dry-run', action='store_true', help='print the commands without running them')
    ap.add_argument('--weights', choices=['auto', 'released', 'trained'], default='auto',
                    help='weights used by infer/validate (auto: the bundle of this run if it exists)')
    args = ap.parse_args(argv)
    import yaml
    config_path = Path(args.config).expanduser()
    try:
        cfg = yaml.safe_load(config_path.read_text())
    except (OSError, yaml.YAMLError) as exc:
        ap.error(f"cannot load configuration {config_path}: {exc}")
    if not isinstance(cfg, dict) or not isinstance(cfg.get('out'), str) or not cfg['out'].strip():
        ap.error("configuration must be a mapping with a nonempty 'out' path")

    want = []
    for s in (x.strip() for x in args.stage.split(',')):
        if s in GROUPS:
            want += GROUPS[s]
        elif s in STAGES:
            want.append(s)
        else:
            raise SystemExit(f"unknown stage '{s}' (stages: {STAGES}; groups: {list(GROUPS)})")
    want = [s for s in STAGES if s in want]           # canonical order, no duplicates

    run = Run(cfg, force=args.force, dry=args.dry_run, weights=args.weights)
    print(f"HERON | config {args.config} | out {run.out} | stages {want}\n")
    for s in want:
        print(f"===== {s} =====")
        getattr(run, s.replace('-', '_'))()
    print("\nHERON run complete.")


if __name__ == '__main__':
    main()
